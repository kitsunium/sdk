// Package main — the package READMEs, written from docs/api (ADR 0167): a
// README is the page a package's directory shows on a forge, and every word
// of it is a doc comment the design holds — the package comment, then each
// exported symbol's declaration and doc — read from the committed docs/api,
// never from the code. An alias shows the declaration, the fields and the
// methods of the type it names, which go/doc, and so gomarkdoc, could not.
// The examples are the one part docs/api does not record: they are code,
// read from the package's own test files.
package main

import (
	"bytes"
	"cmp"
	"fmt"
	"go/ast"
	"go/doc"
	"go/doc/comment"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"unicode"
)

const (
	// readmeFile is a package's README, in its directory.
	readmeFile string = "README.md"
	// readmeHeader opens every README this program writes: what writes it,
	// from what.
	readmeHeader string = "<!-- Code generated by tools/genindex from docs/api. DO NOT EDIT. -->"
	// readmeAdvice is what a drifted README asks for.
	readmeAdvice string = "a README is written from docs/api: edit the doc in design/, run kit gen and `make api`, then `make docs-readme`"
	// sourceBase is where a declaration's file is linked to.
	sourceBase string = "https://github.com/kitsunium/sdk/blob/main/"
	// readmePerm is a README's mode: the files are committed and public.
	readmePerm os.FileMode = 0o644
	// headingLevel is the level a doc comment's heading takes in a README:
	// below the page's title and its sections.
	headingLevel int = 3
)

// readmeRoots are the directories whose packages have a README: the public
// API and the framework a product imports.
var readmeRoots = []string{"pkg/", "framework/"}

// readmePackage is one package a README is written for: its record, its
// module's document, and its directory relative to the repository.
type readmePackage struct {
	pkg *apiPackage
	doc *apiDocument
	dir string
}

// apiIndex is every document's records, by id and by owner, for the
// READMEs: what an alias names is often another package's, another module's.
type apiIndex struct {
	// byID are the records of each id, in document order.
	byID map[string][]*apiSymbol
	// docOf is each id's module document.
	docOf map[string]*apiDocument
	// methods are the method ids of each type id, in document order.
	methods map[string][]string
	// byPackage are the non-method ids of each package, in document order.
	byPackage map[string][]string
}

// indexAPI indexes the documents.
func indexAPI(docs []*apiDocument) *apiIndex {
	ix := &apiIndex{byID: map[string][]*apiSymbol{}, docOf: map[string]*apiDocument{}, methods: map[string][]string{}, byPackage: map[string][]string{}}
	//: every document.
	for _, d := range docs {
		//: every record of it.
		for i := range d.Symbols {
			s := &d.Symbols[i]
			//: the first record of an id files it.
			if _, seen := ix.byID[s.ID]; !seen {
				ix.docOf[s.ID] = d
				//: a method under its type, any other under its package.
				if s.Kind == kindMethod {
					owner := typeIDOf(s.Package, s.Recv)
					ix.methods[owner] = append(ix.methods[owner], s.ID)
				} else {
					ix.byPackage[s.Package] = append(ix.byPackage[s.Package], s.ID)
				}
			}
			ix.byID[s.ID] = append(ix.byID[s.ID], s)
		}
	}
	//: the index.
	return ix
}

// typeIDOf is a named type's id: go:<path>.<Name>, the path's last element's
// dots escaped.
func typeIDOf(pkgPath, name string) string {
	slash := strings.LastIndex(pkgPath, "/")
	//: the escaped path, then the name.
	return idPrefix + pkgPath[:slash+1] + strings.ReplaceAll(pkgPath[slash+1:], ".", "%2e") + "." + name
}

// readmePackages are the packages a README is written for, in directory
// order: each package under readmeRoots that docs/api records, its first
// record (its doc is the same on every cell, the design's).
func readmePackages(docs []*apiDocument) []readmePackage {
	var out []readmePackage
	seen := map[string]bool{}
	//: every document.
	for _, d := range docs {
		//: every package record.
		for i := range d.Packages {
			p := &d.Packages[i]
			dir := path.Join(d.Dir, p.Dir)
			//: once per package, under a README root.
			if seen[p.Path] || !underReadmeRoot(dir) {
				continue
			}
			seen[p.Path] = true
			out = append(out, readmePackage{pkg: p, doc: d, dir: dir})
		}
	}
	slices.SortFunc(out, func(a, b readmePackage) int { return strings.Compare(a.dir, b.dir) })
	//: the packages.
	return out
}

// underReadmeRoot reports whether a directory is under a README root.
func underReadmeRoot(dir string) bool {
	//: any of them.
	for _, r := range readmeRoots {
		//: a prefix of the directory.
		if strings.HasPrefix(dir+"/", r) {
			//: under it.
			return true
		}
	}
	//: no README.
	return false
}

// renderReadmes writes every README in memory, by repository-relative path.
func renderReadmes(root string, docs []*apiDocument) (map[string][]byte, error) {
	ix := indexAPI(docs)
	out := map[string][]byte{}
	//: every package that has a README.
	for _, rp := range readmePackages(docs) {
		examples, err := packageExamples(filepath.Join(root, filepath.FromSlash(rp.dir)))
		//: a test file that does not parse.
		if err != nil {
			//: name the package.
			return nil, fmt.Errorf("%s: %w", rp.dir, err)
		}
		out[path.Join(rp.dir, readmeFile)] = newReadme(ix, rp, examples).render()
	}
	//: the READMEs.
	return out, nil
}

// readme is one README being written.
type readme struct {
	ix       *apiIndex
	rp       readmePackage
	examples map[string][]*doc.Example
	// syms are the package's symbols, by section; names are the names its
	// doc links may resolve to, and members its types' members.
	consts, vars, funcs, types []string
	names, members             map[string]bool
	b                          bytes.Buffer
}

// newReadme gathers what a package's README shows.
func newReadme(ix *apiIndex, rp readmePackage, examples map[string][]*doc.Example) *readme {
	r := &readme{ix: ix, rp: rp, examples: examples, names: map[string]bool{}, members: map[string]bool{}}
	ids := slices.Clone(ix.byPackage[rp.pkg.Path])
	slices.SortStableFunc(ids, func(a, b string) int { return strings.Compare(ix.byID[a][0].Name, ix.byID[b][0].Name) })
	//: every symbol of the package, by section.
	for _, id := range ids {
		s := ix.byID[id][0]
		r.names[s.Name] = true
		//: its section.
		switch s.Kind {
		//: a constant.
		case kindConst:
			r.consts = append(r.consts, id)
		//: a variable.
		case kindVar:
			r.vars = append(r.vars, id)
		//: a function.
		case kindFunc:
			r.funcs = append(r.funcs, id)
		//: a type or an alias.
		default:
			r.types = append(r.types, id)
			//: its methods, its own or its owner's.
			for _, m := range r.methodsOf(s) {
				r.members[s.Name+"."+ix.byID[m][0].Name] = true
			}
		}
	}
	//: ready to render.
	return r
}

// methodsOf are the method ids a type shows: its own, or an alias's owner's.
func (r *readme) methodsOf(s *apiSymbol) []string {
	//: an alias shows the methods of the type it names.
	if s.Kind == kindAlias && s.Owner != "" {
		//: the owner's.
		return r.ix.methods[s.Owner]
	}
	//: its own.
	return r.ix.methods[s.ID]
}

// render writes the README: its header, title and import, the package
// comment, the index, then the constants, variables, functions and types.
func (r *readme) render() []byte {
	p := r.rp.pkg
	fmt.Fprintf(&r.b, "%s\n\n# %s\n\n```go\nimport %q\n```\n\n", readmeHeader, p.Name, p.Path)
	r.docText(p.Doc)
	r.index()
	r.valueSection("Constants", r.consts)
	r.valueSection("Variables", r.vars)
	//: every function.
	for _, id := range r.funcs {
		r.function(id)
	}
	//: every type.
	for _, id := range r.types {
		r.typeSection(id)
	}
	r.b.WriteString("Generated from [docs/api](<" + sourceBase + "docs/api>) by tools/genindex.\n")
	//: the bytes.
	return r.b.Bytes()
}

// index writes the list of the README's sections and symbols.
func (r *readme) index() {
	//: a package that exports nothing has no index.
	if len(r.consts)+len(r.vars)+len(r.funcs)+len(r.types) == 0 {
		return
	}
	r.b.WriteString("## Index\n\n")
	//: the constants' section.
	if len(r.consts) > 0 {
		r.b.WriteString("- [Constants](<#constants>)\n")
	}
	//: the variables' section.
	if len(r.vars) > 0 {
		r.b.WriteString("- [Variables](<#variables>)\n")
	}
	//: each function.
	for _, id := range r.funcs {
		s := r.ix.byID[id][0]
		fmt.Fprintf(&r.b, "- [%s](<#%s>)\n", escapeMarkdown(oneLineDecl(declOf(s, s.Name, ""))), s.Name)
	}
	//: each type, and its methods.
	for _, id := range r.types {
		s := r.ix.byID[id][0]
		fmt.Fprintf(&r.b, "- [type %s](<#%s>)\n", escapeMarkdown(s.Name), s.Name)
		//: its methods.
		for _, m := range r.methodsOf(s) {
			ms := r.ix.byID[m][0]
			fmt.Fprintf(&r.b, "  - [%s](<#%s.%s>)\n", escapeMarkdown(oneLineDecl(declOf(ms, ms.Name, s.Name))), s.Name, ms.Name)
		}
	}
	r.b.WriteString("\n")
}

// valueSection writes the constants' or the variables' section: each one's
// anchor, declaration, code and doc.
func (r *readme) valueSection(title string, ids []string) {
	//: an empty section is not written.
	if len(ids) == 0 {
		return
	}
	fmt.Fprintf(&r.b, "## %s\n\n", title)
	//: each one.
	for _, id := range ids {
		s := r.ix.byID[id][0]
		fmt.Fprintf(&r.b, "<a name=%q></a>\n", s.Name)
		r.forms(id, s.Name, "")
		r.docText(s.Doc)
		r.code(s)
	}
}

// function writes a function's heading, declaration, doc and examples.
func (r *readme) function(id string) {
	s := r.ix.byID[id][0]
	fmt.Fprintf(&r.b, "<a name=%q></a>\n## func [%s](<%s>)\n\n", s.Name, s.Name, r.source(id, s))
	r.forms(id, s.Name, "")
	r.docText(s.Doc)
	r.exampleBlocks(s.Name)
}

// typeSection writes a type: its heading, doc, declaration — an alias's,
// then the declaration of the type it names —, its examples, then its
// methods.
func (r *readme) typeSection(id string) {
	s := r.ix.byID[id][0]
	fmt.Fprintf(&r.b, "<a name=%q></a>\n## type [%s](<%s>)\n\n", s.Name, s.Name, r.source(id, s))
	r.docText(s.Doc)
	r.forms(id, s.Name, "")
	//: an alias shows what it names, which go/doc could not.
	if s.Kind == kindAlias && s.Owner != "" {
		r.owner(s)
	}
	r.exampleBlocks(s.Name)
	//: each method, its own or its owner's.
	for _, m := range r.methodsOf(s) {
		ms := r.ix.byID[m][0]
		fmt.Fprintf(&r.b, "<a name=\"%s.%s\"></a>\n### func \\(%s\\) [%s](<%s>)\n\n", s.Name, ms.Name, escapeMarkdown(s.Name), ms.Name, r.source(m, ms))
		r.forms(m, ms.Name, s.Name)
		r.docText(ms.Doc)
		r.exampleBlocks(s.Name + "_" + ms.Name)
	}
}

// owner writes the type an alias names: its declaration with its fields'
// docs, when docs/api records it; its name alone when it does not (a
// standard-library type).
func (r *readme) owner(s *apiSymbol) {
	//: a type outside docs/api.
	if _, ok := r.ix.byID[s.Owner]; !ok {
		fmt.Fprintf(&r.b, "%s is an alias of `%s`.\n\n", s.Name, strings.TrimPrefix(s.Owner, idPrefix))
		return
	}
	fmt.Fprintf(&r.b, "%s is an alias of `%s`, declared as:\n\n", s.Name, strings.TrimPrefix(s.Owner, idPrefix))
	r.forms(s.Owner, s.Name, "")
}

// forms writes each form of a symbol — one per record, a record of some
// cells only saying which — as a Go block.
func (r *readme) forms(id, name, recv string) {
	records := r.ix.byID[id]
	//: each record.
	for _, s := range records {
		//: a form of some cells only.
		if len(s.Platforms) > 0 {
			fmt.Fprintf(&r.b, "On %s:\n\n", strings.Join(s.Platforms, ", "))
		}
		fmt.Fprintf(&r.b, "```go\n%s\n```\n\n", r.declWithDocs(s, name, recv))
	}
}

// declWithDocs is a record's declaration, a struct's field docs and an
// interface's method docs written above their lines, as gofmt writes them.
func (r *readme) declWithDocs(s *apiSymbol, name, recv string) string {
	decl := declOf(s, name, recv)
	//: only a type's body holds members.
	if s.Kind != kindType {
		//: the declaration as it is.
		return decl
	}
	lines := strings.Split(decl, "\n")
	out := make([]string, 0, len(lines))
	//: each line; a member's gets its doc above it.
	for _, line := range lines {
		//: a member's line, inside the braces.
		if member, ok := memberName(line); ok {
			out = append(out, commentLines("\t", r.memberDoc(s, member))...)
		}
		out = append(out, line)
	}
	//: the declaration.
	return strings.Join(out, "\n")
}

// memberDoc is a struct field's or an interface method's doc.
func (r *readme) memberDoc(s *apiSymbol, member string) string {
	//: a field.
	for _, f := range s.Fields {
		//: by name.
		if f.Name == member {
			//: its doc.
			return f.Doc
		}
	}
	//: an interface's method.
	if ms, ok := r.ix.byID[typeIDOf(s.Package, s.Name)+"."+member]; ok && ms[0].Kind == kindMethod {
		//: its doc.
		return ms[0].Doc
	}
	//: none.
	return ""
}

// memberName is the name a declaration's member line declares — a field's
// first word, an interface method's name, an embedded type's last element —
// and whether the line declares one.
func memberName(line string) (string, bool) {
	//: a member line is indented by one tab.
	if !strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "\t\t") || strings.HasPrefix(line, "\t//") {
		//: none.
		return "", false
	}
	word, rest := leadingWord(strings.TrimPrefix(line, "\t"))
	//: an embedded field's qualified type names its last element.
	if after, ok := strings.CutPrefix(rest, "."); ok {
		word, _ = leadingWord(after)
	}
	//: the word, when there is one.
	return word, word != ""
}

// leadingWord splits the identifier a text opens with from what follows it.
func leadingWord(s string) (word, rest string) {
	end := strings.IndexFunc(s, func(c rune) bool { return !unicode.IsLetter(c) && !unicode.IsDigit(c) && c != '_' })
	//: the whole text is one word.
	if end < 0 {
		//: the word, nothing after.
		return s, ""
	}
	//: the word, then the rest.
	return s[:end], s[end:]
}

// commentLines writes a doc as line comments, each indented.
func commentLines(indent, text string) []string {
	text = strings.TrimRight(text, "\n")
	//: no doc, no line.
	if text == "" {
		//: none.
		return nil
	}
	var out []string
	//: each line of the doc.
	for line := range strings.SplitSeq(text, "\n") {
		//: a blank line, a code line, a text line.
		switch {
		//: a blank one.
		case line == "":
			out = append(out, indent+"//")
		//: a code one.
		case strings.HasPrefix(line, "\t"):
			out = append(out, indent+"//"+line)
		//: any other.
		default:
			out = append(out, indent+"// "+line)
		}
	}
	//: the lines.
	return out
}

// code writes what docs/api says of a value beyond its declaration: the
// symbol it is initialised with, an error code's dotted quad, and a
// sentinel's reason and wire-safe public text.
func (r *readme) code(s *apiSymbol) {
	//: a value that is another package's re-exported.
	if s.Init != "" {
		fmt.Fprintf(&r.b, "Initialised with `%s`.\n\n", strings.TrimPrefix(s.Init, idPrefix))
	}
	//: no code.
	if s.Code == nil {
		return
	}
	//: a sentinel names its reason and its public text too.
	if s.Code.Reason != "" {
		fmt.Fprintf(&r.b, "Code `%s` · reason `%s` · public %q\n\n", s.Code.Value, s.Code.Reason, s.Code.Public)
		return
	}
	fmt.Fprintf(&r.b, "Code `%s`\n\n", s.Code.Value)
}

// source is a record's file, linked at the repository's main branch.
func (r *readme) source(id string, s *apiSymbol) string {
	d := r.ix.docOf[id]
	//: the file, relative to the repository.
	return sourceBase + path.Join(d.Dir, s.File)
}

// docText writes a doc comment as Markdown, the way go/doc/comment prints
// it: its headings below the page's sections, its doc links to the
// README's anchors when they name this package, to pkg.go.dev otherwise.
func (r *readme) docText(text string) {
	//: no doc, no paragraph.
	if strings.TrimSpace(text) == "" {
		return
	}
	pkgPath := r.rp.pkg.Path
	parser := comment.Parser{
		LookupSym: func(recv, name string) bool {
			//: a member, or a name of the package.
			if recv != "" {
				//: a type's member.
				return r.members[recv+"."+name]
			}
			//: a name.
			return r.names[name]
		},
	}
	printer := comment.Printer{
		HeadingLevel: headingLevel,
		// A heading gets no {#id}: GitHub prints that syntax as text.
		HeadingID: func(*comment.Heading) string { return "" },
		DocLinkURL: func(link *comment.DocLink) string {
			anchor := link.Name
			//: a member's anchor.
			if link.Recv != "" {
				anchor = link.Recv + "." + link.Name
			}
			//: this package's names are anchors of this page.
			if link.ImportPath == "" || link.ImportPath == pkgPath {
				//: the anchor.
				return "#" + anchor
			}
			//: another package's, at pkg.go.dev.
			return "https://pkg.go.dev/" + link.ImportPath + cmp.Or(prefixed("#", anchor), "")
		},
	}
	parsed := parser.Parse(text)
	//: block by block: a code block fenced, as a forge renders it best.
	for _, block := range parsed.Content {
		//: a code block.
		if code, ok := block.(*comment.Code); ok {
			fmt.Fprintf(&r.b, "```\n%s```\n\n", code.Text)
			continue
		}
		r.b.Write(printer.Markdown(&comment.Doc{Content: []comment.Block{block}, Links: parsed.Links}))
		r.b.WriteString("\n")
	}
}

// prefixed is s after prefix, or "" when s is.
func prefixed(prefix, s string) string {
	//: nothing to prefix.
	if s == "" {
		//: none.
		return ""
	}
	//: the prefixed text.
	return prefix + s
}

// exampleBlocks writes the examples of a symbol, by go/doc's name: "" the
// package's, F a function's, T_M a method's.
func (r *readme) exampleBlocks(name string) {
	//: each example, in name order.
	for _, ex := range r.examples[name] {
		title := "Example"
		//: a suffixed example says its suffix.
		if ex.Suffix != "" {
			title = fmt.Sprintf("Example (%s)", ex.Suffix)
		}
		fmt.Fprintf(&r.b, "<details><summary>%s</summary>\n<p>\n\n", title)
		r.docText(ex.Doc)
		//: its code, when go/format prints it.
		if code, ok := exampleCode(ex); ok {
			fmt.Fprintf(&r.b, "```go\n%s\n```\n\n", code)
		}
		//: an example that prints says what.
		if ex.Output != "" {
			fmt.Fprintf(&r.b, "#### Output\n\n```\n%s\n```\n\n", strings.TrimRight(ex.Output, "\n"))
		}
		r.b.WriteString("</p>\n</details>\n\n")
	}
}

// exampleCode is an example's code — the whole program go/doc makes of it
// when it can, else its body — and whether go/format prints it.
func exampleCode(ex *doc.Example) (string, bool) {
	var b bytes.Buffer
	fset := token.NewFileSet()
	//: a playable program.
	if ex.Play != nil {
		//: the program, formatted.
		if err := format.Node(&b, fset, ex.Play); err == nil {
			//: as gofmt writes it.
			return strings.TrimRight(b.String(), "\n"), true
		}
		b.Reset()
	}
	//: the body alone.
	if err := format.Node(&b, fset, ex.Code); err != nil {
		//: nothing printable.
		return "", false
	}
	code := strings.TrimRight(b.String(), "\n")
	//: a block's braces are no part of the example.
	if strings.HasPrefix(code, "{\n") && strings.HasSuffix(code, "\n}") {
		code = dedentTab(code[2 : len(code)-2])
	}
	//: the code.
	return code, true
}

// dedentTab removes one leading tab from every line.
func dedentTab(s string) string {
	lines := strings.Split(s, "\n")
	//: each line.
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "\t")
	}
	//: the lines.
	return strings.Join(lines, "\n")
}

// packageExamples reads the examples of a package's test files, by the name
// of what each documents ("" the package, F, T, T_M), each list in name
// order.
func packageExamples(dir string) (map[string][]*doc.Example, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
	//: the pattern is a constant the glob syntax accepts.
	if err != nil {
		//: as the glob said it.
		return nil, err
	}
	slices.Sort(names)
	fset := token.NewFileSet()
	var files []*ast.File
	//: every test file of the package.
	for _, name := range names {
		f, perr := parser.ParseFile(fset, name, nil, parser.ParseComments|parser.SkipObjectResolution)
		//: a test file that does not parse.
		if perr != nil {
			//: as the parser said it.
			return nil, perr
		}
		files = append(files, f)
	}
	out := map[string][]*doc.Example{}
	//: every example, under what it documents.
	for _, ex := range doc.Examples(files...) {
		out[ex.Name] = append(out[ex.Name], ex)
	}
	//: each list in name order.
	for k := range out {
		slices.SortFunc(out[k], func(a, b *doc.Example) int { return strings.Compare(a.Suffix, b.Suffix) })
	}
	//: the examples.
	return out, nil
}

// declOf is a record's declaration as gofmt starts it, written under name
// (an alias shows its owner's under its own) and, for a method, recv.
func declOf(s *apiSymbol, name, recv string) string {
	spelled := s.Spelled
	//: by kind.
	switch s.Kind {
	//: a function.
	case kindFunc:
		//: func Name(…).
		return "func " + name + strings.TrimPrefix(spelled, "func")
	//: a method.
	case kindMethod:
		star := ""
		//: a pointer receiver.
		if strings.Contains(s.ID, ".(*") {
			star = "*"
		}
		//: func (T) Name(…).
		return "func (" + star + cmp.Or(recv, s.Recv) + ") " + name + strings.TrimPrefix(spelled, "func")
	//: a defined type.
	case kindType:
		//: type Name ….
		return typeDecl(name, spelled, s.Fields)
	//: an alias.
	case kindAlias:
		params, rest := leadingTypeParams(spelled)
		//: type Name = ….
		return "type " + name + params + " = " + rest
	//: a constant.
	case kindConst:
		//: an untyped one has no type.
		if strings.HasPrefix(spelled, "untyped ") {
			//: const Name = value.
			return "const " + name + " = " + s.Value
		}
		//: const Name T = value.
		return "const " + name + " " + spelled + " = " + s.Value
	//: a variable.
	default:
		//: var Name T.
		return "var " + name + " " + spelled
	}
}

// typeDecl is a defined type's declaration: a struct's fields and an
// interface's methods on lines of their own, as gofmt writes them.
func typeDecl(name, spelled string, fields []apiField) string {
	params, rest := leadingTypeParams(spelled)
	keyword, body, ok := braced(rest)
	//: neither a struct nor an interface.
	if !ok {
		//: type Name underlying.
		return "type " + name + params + " " + rest
	}
	var lines []string
	//: an interface's methods and embeds, as written.
	if keyword == "interface" {
		lines = splitTopLevel(body, ';')
	} else {
		lines = fieldLines(fields)
	}
	//: an empty body.
	if len(lines) == 0 {
		//: braces alone.
		return "type " + name + params + " " + keyword + "{}"
	}
	//: the body over several lines.
	return "type " + name + params + " " + keyword + " {\n\t" + strings.Join(lines, "\n\t") + "\n}"
}

// fieldLines are a struct's exported fields, aligned as gofmt aligns them.
func fieldLines(fields []apiField) []string {
	width, typeWidth := 0, 0
	//: the widest name, and the widest type of a tagged field.
	for _, f := range fields {
		//: an embedded field has no name column.
		if f.Embedded {
			continue
		}
		width = max(width, len(f.Name))
		//: a tag aligns the types before it.
		if f.Tag != "" {
			typeWidth = max(typeWidth, len(f.Type))
		}
	}
	out := make([]string, 0, len(fields))
	//: each field.
	for _, f := range fields {
		//: an embedded one is its type.
		if f.Embedded {
			out = append(out, strings.TrimSpace(f.Type+" "+quoteTag(f.Tag)))
			continue
		}
		//: a tagged one aligns its type.
		if f.Tag != "" {
			out = append(out, fmt.Sprintf("%-*s %-*s %s", width, f.Name, typeWidth, f.Type, quoteTag(f.Tag)))
			continue
		}
		out = append(out, fmt.Sprintf("%-*s %s", width, f.Name, f.Type))
	}
	//: the lines.
	return out
}

// quoteTag writes a struct tag as Go does: between backquotes when it holds
// none.
func quoteTag(tag string) string {
	//: no tag.
	if tag == "" {
		//: nothing.
		return ""
	}
	//: a tag with a backquote is a string literal.
	if strings.Contains(tag, "`") {
		//: quoted.
		return fmt.Sprintf("%q", tag)
	}
	//: raw.
	return "`" + tag + "`"
}

// braced splits "struct{…}" or "interface{…}" into its keyword and body.
func braced(s string) (keyword, body string, ok bool) {
	//: the two keywords a body follows.
	for _, k := range []string{"struct", "interface"} {
		//: k{…}.
		if strings.HasPrefix(s, k+"{") && strings.HasSuffix(s, "}") {
			//: its parts.
			return k, s[len(k)+1 : len(s)-1], true
		}
	}
	//: none.
	return "", "", false
}

// leadingTypeParams splits a type parameter list off the front of a
// signature: "[K comparable] map[K]V" gives "[K comparable]", "map[K]V".
func leadingTypeParams(sig string) (params, rest string) {
	//: no list.
	if !strings.HasPrefix(sig, "[") {
		//: the signature.
		return "", sig
	}
	depth := 0
	//: the bracket that closes the list.
	for i, c := range sig {
		//: brackets nest.
		switch c {
		//: one deeper.
		case '[':
			depth++
		//: one shallower; zero closes it.
		case ']':
			depth--
			//: the list's end.
			if depth == 0 {
				//: the list, then the rest.
				return sig[:i+1], strings.TrimSpace(sig[i+1:])
			}
		//: any other rune.
		default:
		}
	}
	//: an unbalanced list is none.
	return "", sig
}

// splitTopLevel splits s at each sep outside brackets, braces, parentheses
// and quotes.
func splitTopLevel(s string, sep rune) []string {
	var out []string
	var sc topLevelScan
	start := 0
	//: each rune; a separator at the top splits.
	for i, c := range s {
		//: a split.
		if sc.step(c, sep) {
			out = append(out, s[start:i])
			start = i + 1
		}
	}
	out = append(out, s[start:])
	parts := out[:0]
	//: each part, trimmed, empty ones left out.
	for _, p := range out {
		//: a part with text.
		if p = strings.TrimSpace(p); p != "" {
			parts = append(parts, p)
		}
	}
	//: the parts.
	return parts
}

// topLevelScan is where a scan of a declaration stands: how deep in
// brackets, and inside which quote.
type topLevelScan struct {
	depth   int
	quote   rune
	escaped bool
}

// step reads one rune and reports whether it is sep at the top level.
func (sc *topLevelScan) step(c, sep rune) bool {
	//: inside a quoted string.
	if sc.quote != 0 {
		sc.escaped, sc.quote = closesQuote(c, sc.quote, sc.escaped)
		//: never a split.
		return false
	}
	//: what the rune opens, closes or splits.
	switch {
	//: a quote opens.
	case c == '"' || c == '`':
		sc.quote = c
	//: a bracket opens.
	case strings.ContainsRune("([{", c):
		sc.depth++
	//: a bracket closes.
	case strings.ContainsRune(")]}", c):
		sc.depth--
	//: any other.
	default:
	}
	//: a separator at the top.
	return c == sep && sc.depth == 0
}

// closesQuote steps a quoted string by one rune: whether the next rune is
// escaped, and the quote still open (0 when c closed it).
func closesQuote(c, quote rune, escaped bool) (bool, rune) {
	//: an escaped rune is part of the string.
	if escaped {
		//: no longer escaped.
		return false, quote
	}
	//: a backslash escapes the next rune of a "string".
	if c == '\\' && quote == '"' {
		//: escaped.
		return true, quote
	}
	//: the quote that opened it closes it.
	if c == quote {
		//: closed.
		return false, 0
	}
	//: still inside.
	return false, quote
}

// oneLineDecl is a declaration on one line, for the index.
func oneLineDecl(decl string) string {
	first, _, _ := strings.Cut(decl, "\n")
	//: a body is elided.
	if strings.HasSuffix(first, "{") {
		first = strings.TrimSuffix(first, " {")
	}
	//: the line.
	return first
}

// escapeMarkdown escapes what Markdown would read as markup in a link's
// text.
func escapeMarkdown(s string) string {
	var b strings.Builder
	//: each rune.
	for _, c := range s {
		//: markup characters take a backslash.
		if strings.ContainsRune("\\`*_[]()<>#|", c) {
			b.WriteRune('\\')
		}
		b.WriteRune(c)
	}
	//: the escaped text.
	return b.String()
}

// runWriteReadmes writes every README from the committed docs/api, and
// removes a README this program wrote for a package docs/api no longer
// records. It returns the process's exit status.
func runWriteReadmes(root string, out io.Writer) int {
	docs, err := readDocuments(root)
	//: nothing is written from a docs/api that could not be read.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed run.
		return 1
	}
	files, err := renderReadmes(root, docs)
	//: a README that cannot be written.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed run.
		return 1
	}
	//: each README.
	for _, rel := range sortedKeys(files) {
		//: the file's bytes.
		if werr := os.WriteFile(filepath.Join(root, filepath.FromSlash(rel)), files[rel], readmePerm); werr != nil {
			fmt.Fprintf(out, "genindex: write %s: %v\n", rel, werr)
			//: a failed run.
			return 1
		}
	}
	stale, err := staleReadmes(root, files)
	//: the tree could not be walked.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed run.
		return 1
	}
	//: each README of a package that is gone.
	for _, rel := range stale {
		//: removed.
		if rerr := os.Remove(filepath.Join(root, filepath.FromSlash(rel))); rerr != nil {
			fmt.Fprintf(out, "genindex: remove %s: %v\n", rel, rerr)
			//: a failed run.
			return 1
		}
	}
	fmt.Fprintf(out, "genindex: wrote %d READMEs from docs/api, removed %d\n", len(files), len(stale))
	//: written.
	return 0
}

// runCheckReadmes compares every README with what -write-readmes writes,
// naming each that differs, is missing or is stale. It returns the
// process's exit status.
func runCheckReadmes(root string, out io.Writer) int {
	docs, err := readDocuments(root)
	//: docs/api could not be read: nothing can be vouched for.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed check.
		return 1
	}
	files, err := renderReadmes(root, docs)
	//: a README that cannot be written.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed check.
		return 1
	}
	var findings []string
	//: each README.
	for _, rel := range sortedKeys(files) {
		got, rerr := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		//: what differs.
		switch {
		//: missing.
		case rerr != nil:
			findings = append(findings, rel+": missing")
		//: different bytes.
		case !bytes.Equal(got, files[rel]):
			findings = append(findings, rel+": differs from what docs/api writes")
		//: the same.
		default:
		}
	}
	stale, err := staleReadmes(root, files)
	//: the tree could not be walked.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed check.
		return 1
	}
	//: a README of a package docs/api no longer records.
	for _, rel := range stale {
		findings = append(findings, rel+": stale — docs/api records no package here")
	}
	//: every README is docs/api's.
	if len(findings) == 0 {
		fmt.Fprintf(out, "genindex: the %d READMEs are what docs/api writes\n", len(files))
		//: a passing check.
		return 0
	}
	//: each finding.
	for _, f := range findings {
		fmt.Fprintf(out, "%s\n", f)
	}
	fmt.Fprintf(out, "genindex: %d README(s) drift; %s\n", len(findings), readmeAdvice)
	//: a failed check.
	return 1
}

// staleReadmes are the READMEs under the README roots that open with this
// program's header and that it does not write now, by repository-relative
// path.
func staleReadmes(root string, want map[string][]byte) ([]string, error) {
	var out []string
	//: each root.
	for _, r := range readmeRoots {
		base := filepath.Join(root, filepath.FromSlash(r))
		werr := filepath.WalkDir(base, func(p string, d os.DirEntry, err error) error {
			//: a directory that cannot be read.
			if err != nil {
				//: as the walk said it.
				return err
			}
			//: a README this program wrote and does not write now.
			if rel := relSlash(root, p); isStaleReadme(p, rel, d, want) {
				out = append(out, rel)
			}
			//: on.
			return nil
		})
		//: a missing root has no README.
		if werr != nil && !os.IsNotExist(werr) {
			//: as the walk said it.
			return nil, werr
		}
	}
	slices.Sort(out)
	//: the stale READMEs.
	return out, nil
}

// isStaleReadme reports whether an entry of the walk is a README this
// program wrote — its first line the header — that it does not write now.
func isStaleReadme(p, rel string, d os.DirEntry, want map[string][]byte) bool {
	//: only a README.
	if d.IsDir() || d.Name() != readmeFile {
		//: not one.
		return false
	}
	//: one this program writes now.
	if _, ok := want[rel]; ok {
		//: not stale.
		return false
	}
	first, _, err := readFirstLine(p)
	//: one this program wrote.
	return err == nil && first == readmeHeader
}
