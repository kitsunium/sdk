// Package main — docs/error-codes.yaml, the SDK's dotted-quad error codes,
// written from docs/api (-write-error-codes, `make error-codes`) and checked
// against it (-check-error-codes, check-error-codes-drift.sh). docs/api is
// written from the code and `make api-check` holds it to the code, so the
// file is the code's twice over: no grep reads a source file to make it.
package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"fmt"
	"io"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const (
	// errorCodesFile is the file, relative to the repository's root.
	errorCodesFile string = "docs/error-codes.yaml"
	// codePrefix starts the name of every constant that declares a code:
	// the errs package's masks are of the code type and no code.
	codePrefix string = "Code"
	// quadParts is how many elements a dotted quad has.
	quadParts int = 4
	// quadMax is the largest value of one element of a dotted quad.
	quadMax uint64 = 255
	// errorCodesAdvice is the remedy every finding of the check ends with.
	errorCodesAdvice string = "docs/error-codes.yaml is written from docs/api: run `make error-codes` (or `make api`) and commit the result"
	// errorCodesHeader opens the file: what it is and where it comes from.
	errorCodesHeader string = `# GENERATED by tools/genindex -write-error-codes from docs/api — DO NOT EDIT BY HAND.
# Regenerate with: make error-codes (make api runs it after writing docs/api)
#
# The SDK's dotted-quad error codes (MM.LL.PP.SS, ADR 0005/0006), one entry per
# errs.Code constant a package of the workspace declares under a name starting
# with Code: a re-export allocates nothing and is no entry, and the errs
# package's masks are of the code type but are no code. docs/api is written
# from the code (make api) and make api-check holds it there; the executable
# source of truth stays the AST audits in internal/kernel/errs (ADR 0005, ADR
# 0035).
codes:
`
)

// errorCode is one entry of docs/error-codes.yaml.
type errorCode struct {
	// quad is the code's four elements, MM, LL, PP and SS.
	quad [quadParts]uint64
	// name is the constant's name.
	name string
	// dir is the declaring package's directory, relative to the
	// repository's root.
	dir string
}

// dotted is the code as MM.LL.PP.SS.
func (c errorCode) dotted() string {
	parts := make([]string, 0, quadParts)
	//: each element in decimal.
	for _, e := range c.quad {
		parts = append(parts, strconv.FormatUint(e, decimal))
	}
	//: joined by dots.
	return strings.Join(parts, ".")
}

// hex is the code as its constants write it: 0xMM_LL_PP_SS.
func (c errorCode) hex() string {
	//: two upper-case digits per element.
	return fmt.Sprintf("0x%02X_%02X_%02X_%02X", c.quad[0], c.quad[1], c.quad[2], c.quad[3])
}

// parseQuad reads a dotted quad, each element 0 to 255.
func parseQuad(s string) ([quadParts]uint64, error) {
	var out [quadParts]uint64
	parts := strings.Split(s, ".")
	//: four elements, never fewer or more.
	if len(parts) != quadParts {
		//: name the value.
		return out, fmt.Errorf("%q is no dotted quad", s)
	}
	//: each element is one byte.
	for i, p := range parts {
		n, err := strconv.ParseUint(p, decimal, quadShift)
		//: a value out of a byte's range, or no number.
		if err != nil || n > quadMax {
			//: name the value.
			return out, fmt.Errorf("%q is no dotted quad", s)
		}
		out[i] = n
	}
	//: the four elements.
	return out, nil
}

// errorCodes are the codes the documents declare: every constant record with
// a code, no initializer naming another symbol and a name starting with
// codePrefix, once per package and name, sorted by value, then by package and
// name. A constant read with two values on two cells is refused.
func errorCodes(docs []*apiDocument) ([]errorCode, error) {
	seen := map[string]errorCode{}
	//: every module's document.
	for _, doc := range docs {
		//: a document whose codes cannot be read stops the run.
		if err := documentCodes(doc, seen); err != nil {
			//: as it failed.
			return nil, err
		}
	}
	out := slices.Collect(maps.Values(seen))
	slices.SortFunc(out, compareErrorCodes)
	//: in value order.
	return out, nil
}

// documentCodes adds one document's codes to seen, by symbol id.
func documentCodes(doc *apiDocument, seen map[string]errorCode) error {
	dirs := packageDirs(doc)
	//: every symbol of it.
	for i := range doc.Symbols {
		s := &doc.Symbols[i]
		//: a constant that declares a code; a re-export names its origin.
		if !declaresCode(s) {
			continue
		}
		quad, err := parseQuad(s.Code.Value)
		//: a code docs/api cannot have written.
		if err != nil {
			//: name the symbol.
			return fmt.Errorf("%s: %w", s.ID, err)
		}
		c := errorCode{quad: quad, name: s.Name, dir: dirs[s.Package]}
		//: one constant read with two values on two cells.
		if prev, dup := seen[s.ID]; dup && prev.quad != c.quad {
			//: name both.
			return fmt.Errorf("%s is %s on some cells and %s on others", s.ID, prev.dotted(), c.dotted())
		}
		seen[s.ID] = c
	}
	//: every code of the document.
	return nil
}

// declaresCode reports whether a record is a constant that declares a code:
// a code, no initializer naming another constant, a name starting with
// codePrefix.
func declaresCode(s *apiSymbol) bool {
	//: the three conditions.
	return s.Kind == kindConst && s.Code != nil && s.Init == "" && strings.HasPrefix(s.Name, codePrefix)
}

// compareErrorCodes orders entries by value, then by package and name.
func compareErrorCodes(a, b errorCode) int {
	//: the first element that differs decides.
	for i := range quadParts {
		//: a different element.
		if a.quad[i] != b.quad[i] {
			//: ascending.
			return cmp.Compare(a.quad[i], b.quad[i])
		}
	}
	//: equal values: the package, then the name.
	if a.dir != b.dir {
		//: by directory.
		return strings.Compare(a.dir, b.dir)
	}
	//: by name.
	return strings.Compare(a.name, b.name)
}

// packageDirs maps a document's packages to their directories relative to
// the repository's root.
func packageDirs(doc *apiDocument) map[string]string {
	out := make(map[string]string, len(doc.Packages))
	//: the module's directory joined with each package's.
	for _, p := range doc.Packages {
		out[p.Path] = path.Join(doc.Dir, p.Dir)
	}
	//: by import path.
	return out
}

// encodeErrorCodes writes the file's bytes.
func encodeErrorCodes(codes []errorCode) []byte {
	var b bytes.Buffer
	b.WriteString(errorCodesHeader)
	//: one entry per code, four lines each.
	for _, c := range codes {
		fmt.Fprintf(&b, "  - code: %q\n    const: %s\n    hex: %q\n    package: %s\n", c.dotted(), c.name, c.hex(), c.dir)
	}
	//: the file.
	return b.Bytes()
}

// readDocuments reads every committed docs/api document, in name order. A
// document of another format is refused: its records would be misread.
func readDocuments(root string) ([]*apiDocument, error) {
	names, err := existingDocuments(root)
	//: a docs/api that cannot be listed.
	if err != nil {
		//: as listed.
		return nil, err
	}
	//: no document: nothing to write the file from.
	if len(names) == 0 {
		//: run make api first.
		return nil, fmt.Errorf("%s holds no document: run `make api`", apiDir)
	}
	out := make([]*apiDocument, 0, len(names))
	//: each document.
	for _, name := range names {
		doc, derr := readDocument(root, name)
		//: a document that cannot be read.
		if derr != nil {
			//: as it failed.
			return nil, derr
		}
		out = append(out, doc)
	}
	//: the documents.
	return out, nil
}

// readDocument reads and decodes one committed document, strictly.
func readDocument(root, name string) (*apiDocument, error) {
	raw, err := os.ReadFile(documentPath(root, name))
	//: a file that cannot be read.
	if err != nil {
		//: name it.
		return nil, fmt.Errorf("read %s/%s%s: %w", apiDir, name, apiExt, err)
	}
	doc := &apiDocument{}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	//: a member this program does not write is another format.
	if derr := dec.Decode(doc); derr != nil {
		//: name the document.
		return nil, fmt.Errorf("decode %s/%s%s: %w", apiDir, name, apiExt, derr)
	}
	//: the format this program writes, and no other.
	if doc.Format != apiFormat {
		//: name both.
		return nil, fmt.Errorf("%s/%s%s is format %q, want %q", apiDir, name, apiExt, doc.Format, apiFormat)
	}
	//: the document.
	return doc, nil
}

// errorCodesFromRepository reads docs/api under root and returns the file's
// bytes and how many codes it lists.
func errorCodesFromRepository(root string) ([]byte, int, error) {
	docs, err := readDocuments(root)
	//: docs/api could not be read.
	if err != nil {
		//: as it failed.
		return nil, 0, err
	}
	codes, cerr := errorCodes(docs)
	//: a code docs/api could not have written.
	if cerr != nil {
		//: as it failed.
		return nil, 0, cerr
	}
	//: the bytes and the count.
	return encodeErrorCodes(codes), len(codes), nil
}

// runWriteErrorCodes writes docs/error-codes.yaml from docs/api. It returns
// the process's exit status.
func runWriteErrorCodes(root string, out io.Writer) int {
	raw, n, err := errorCodesFromRepository(root)
	//: nothing is written from a docs/api that could not be read.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed run.
		return 1
	}
	target := filepath.Join(root, filepath.FromSlash(errorCodesFile))
	//: the file's bytes.
	if werr := os.WriteFile(target, raw, apiFilePerm); werr != nil {
		fmt.Fprintf(out, "genindex: write %s: %v\n", errorCodesFile, werr)
		//: a failed run.
		return 1
	}
	fmt.Fprintf(out, "genindex: wrote %s (%d codes)\n", errorCodesFile, n)
	//: written.
	return 0
}

// runCheckErrorCodes compares docs/error-codes.yaml with what docs/api
// writes, naming each entry added or removed. It returns the process's exit
// status.
func runCheckErrorCodes(root string, out io.Writer) int {
	want, n, err := errorCodesFromRepository(root)
	//: docs/api could not be read: nothing can be vouched for.
	if err != nil {
		fmt.Fprintf(out, "genindex: %v\n", err)
		//: a failed check.
		return 1
	}
	got, rerr := os.ReadFile(filepath.Join(root, filepath.FromSlash(errorCodesFile)))
	//: no file at all.
	if rerr != nil {
		fmt.Fprintf(out, "genindex: %s cannot be read (%v); %s\n", errorCodesFile, rerr, errorCodesAdvice)
		//: a failed check.
		return 1
	}
	//: the same bytes.
	if bytes.Equal(got, want) {
		fmt.Fprintf(out, "genindex: %s lists the %d codes docs/api declares\n", errorCodesFile, n)
		//: a passing check.
		return 0
	}
	//: one line per entry that differs, the remedy last.
	for _, line := range errorCodesDrift(got, want) {
		fmt.Fprintln(out, line)
	}
	fmt.Fprintf(out, "genindex: %s differs from docs/api; %s\n", errorCodesFile, errorCodesAdvice)
	//: a failing check.
	return 1
}

// errorCodesDrift names the entries one file lists and the other does not,
// bounded; the bytes may also differ outside the entries (the header).
func errorCodesDrift(got, want []byte) []string {
	have, should := entryKeys(got), entryKeys(want)
	var out []string
	//: listed and not declared.
	for _, k := range slices.Sorted(maps.Keys(have)) {
		//: an entry docs/api does not write.
		if !should[k] {
			out = append(out, "  listed, not declared: "+k)
		}
	}
	//: declared and not listed.
	for _, k := range slices.Sorted(maps.Keys(should)) {
		//: an entry the file lacks.
		if !have[k] {
			out = append(out, "  declared, not listed: "+k)
		}
	}
	//: a long drift is cut.
	if len(out) > maxDriftLines {
		out = append(out[:maxDriftLines], fmt.Sprintf("  … and %d more", len(out)-maxDriftLines))
	}
	//: the entries, possibly none when only the rest of the bytes differ.
	return out
}

// entryKeys reads a file's entries as package.Name code.
func entryKeys(raw []byte) map[string]bool {
	out := map[string]bool{}
	var code, name string
	//: line by line, the four lines of an entry.
	for line := range strings.SplitSeq(string(raw), "\n") {
		line = strings.TrimSpace(line)
		//: which line of an entry.
		switch {
		//: the code opens an entry.
		case strings.HasPrefix(line, "- code: "):
			code = strings.Trim(strings.TrimPrefix(line, "- code: "), `"`)
		//: the constant's name.
		case strings.HasPrefix(line, "const: "):
			name = strings.TrimPrefix(line, "const: ")
		//: the package closes it.
		case strings.HasPrefix(line, "package: "):
			out[strings.TrimPrefix(line, "package: ")+"."+name+" "+code] = true
		}
	}
	//: the entries.
	return out
}
