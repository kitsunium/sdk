// The node kinds of the graph: a closed set, written by name on the wire.

package core

// The node kinds.
const (
	// KindService groups the nodes of one bounded context.
	KindService NodeKind = "service"
	// KindEndpoint is an HTTP endpoint with typed request and response.
	KindEndpoint NodeKind = "endpoint"
	// KindStore is a typed, keyed collection of entities.
	KindStore NodeKind = "store"
	// KindTopic is an asynchronous, at-least-once message channel.
	KindTopic NodeKind = "topic"
	// KindSubscription consumes one topic.
	KindSubscription NodeKind = "subscription"
	// KindWorkflow is a state machine over the entities of one store.
	KindWorkflow NodeKind = "workflow"
	// KindJob is scheduled work: a fixed interval or a cron expression.
	KindJob NodeKind = "job"
	// KindFrontend is static assets served by the product.
	KindFrontend NodeKind = "frontend"
	// KindExternal stands for everything outside the product.
	KindExternal NodeKind = "external"
	// KindAuth is the app's authentication handler: it turns a request's
	// credentials into a user, in front of every endpoint that asks for one.
	KindAuth NodeKind = "auth"
	// KindMailer is outbound mail: a durable outbox, and the transport that
	// empties it — SMTP, or the capture of dev and tests.
	KindMailer NodeKind = "mailer"
	// KindLoop is a long-running loop of the daemon: declared (kit owns the
	// wait, the product the work) or hand-written (a goroutine kit supervises).
	KindLoop NodeKind = "loop"
	// KindSecret is a secret the product declares: provided by the operator,
	// or generated by kit and rotated on a schedule. Its value is never in a
	// graph.
	KindSecret NodeKind = "secret"
	// KindPort is an operation a service needs and does not implement: a
	// typed request, a typed response, a name. What it calls — another
	// service's endpoint, the app's binding, its own fallback — is decided
	// when the app starts, and drawn as a declared edge from the port.
	KindPort NodeKind = "port"
	// KindCommand is an operation that changes something: a typed input, a
	// typed result, one handler, the pipeline of its kind. It is dispatched,
	// on its caller's goroutine or through its own queue.
	KindCommand NodeKind = "command"
	// KindQuery is an operation that reads and changes nothing: a typed
	// input, a typed result, one handler. It is asked.
	KindQuery NodeKind = "query"
	// KindBinary is one executable the product ships. It holds process
	// roles; its ID is "binary:<name>".
	KindBinary NodeKind = "binary"
	// KindRole is one process role of a binary — "statusline" and
	// "statusline daemon" are two roles of one binary. Its root package is
	// generated wiring; two roles talk through their contract only. Its ID
	// is "binary:<binary>/role/<name>".
	KindRole NodeKind = "role"
	// KindCLI is a short command-line command: it parses its arguments,
	// runs once and exits with a typed status.
	KindCLI NodeKind = "cli"
	// KindListener accepts connections that are not HTTP: a private Unix
	// socket, a named pipe. It is an inbound port like an endpoint.
	KindListener NodeKind = "listener"
	// KindLibrary is a package shared between components, declared so the
	// components that use it are allowed to import it. Its ID is
	// "library:<name>".
	KindLibrary NodeKind = "library"
	// KindPresentation turns a service's results into what a reader sees:
	// a rendered line, a page, a report.
	KindPresentation NodeKind = "presentation"
)

// NodeKind is the closed set of building blocks a kit product is made of.
// It is a wire format — the graph's JSON and the Studio's TypeScript unions
// carry these names —, so it stays a string.
//
//ktn:wire-format
type NodeKind string
