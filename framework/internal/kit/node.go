// Package kit — nodes: what every declaration shares, and its source position.
package kit

import (
	"context"
	"net/url"
	"reflect"
	"runtime"
	"strings"

	"github.com/kitsunium/sdk/framework/model"
)

// facadePackage is framework/kit, the package a product imports: its
// functions forward to this one's, and a frame of it is never a declaration.
const facadePackage string = "github.com/kitsunium/sdk/framework/kit"

// pos is a source position captured at runtime. file is whatever the
// compiler recorded: absolute in a normal build, module-prefixed under
// -trimpath. The App relativizes it once it knows the module root.
type pos struct {
	file string
	line int
	fn   string
	// pkg is the import path of the package whose code is there, when the
	// runtime says it: a declaration's Go module decides who owns it, and
	// where its file is relative to (gomodule.go).
	pkg string
}

// callerPos returns the position of the code that called the kit function
// calling callerPos: the declaration site of a building block.
//
// Every exported constructor that calls it is marked //go:noinline. A
// constructor inlined into a package's generated init function loses the
// position of its call site — the frame reads <autogenerated>:1 — and the
// diagram would point nowhere. The tests pin the positions.
func callerPos() pos { return callerFrame(3) }

// callerFrame returns the position skip frames up: 0 is callerFrame itself.
// Every constructor must reach it at the same depth, which the tests pin. A
// frame of the facade — framework/kit, whose functions only forward here —
// is not a declaration's: the position is the frame that called the facade.
func callerFrame(skip int) pos {
	for ; ; skip++ {
		pc, file, line, ok := runtime.Caller(skip)
		if !ok {
			return pos{}
		}
		p := pos{file: file, line: line}
		if f := runtime.FuncForPC(pc); f != nil {
			p.pkg, _ = packageOf(f.Name())
		}
		if p.pkg != facadePackage {
			return p
		}
	}
}

// packageOf is the import path of the package a function belongs to, read
// from the name the runtime gives it — "example.com/shop/orders.init",
// "example.com/shop/orders.(*T).M" —, the dots of its last element escaped
// there as %2e; "" when the name says none.
func packageOf(fn string) (string, bool) {
	slash := strings.LastIndex(fn, "/")
	dot := strings.Index(fn[slash+1:], ".")
	if dot < 0 {
		return "", false
	}
	pkg := fn[:slash+1+dot]
	if unescaped, err := url.PathUnescape(pkg); err == nil {
		return unescaped, true
	}
	return pkg, true
}

// isClosureName reports whether qualified is a name the compiler gives a
// function literal or a method-value wrapper — `….func1`, `….func2.3`,
// `glob.…`, `…-fm` —, which is not a name a developer wrote. It is written
// out rather than a regular expression compiled at every start.
func isClosureName(qualified string) bool {
	if strings.HasPrefix(qualified, "glob.") || strings.HasSuffix(qualified, "-fm") {
		return true
	}
	_, rest, found := strings.CutLast(qualified, ".func")
	if !found {
		return false
	}
	// What follows ".func" is digits, then any number of ".digits".
	for part := range strings.SplitSeq(rest, ".") {
		if part == "" || strings.Trim(part, "0123456789") != "" {
			return false
		}
	}
	return true
}

// funcInfo describes a function value: where its body starts, its qualified
// name, and the short name a developer gave it, when it has one.
//
// The short name is the join key with the static analyzer, which derives it
// from the syntax: a named function or method keeps its name, a literal has
// none. The format of runtime.FuncForPC names is not a documented contract,
// so this is kept deliberately narrow and anything unexpected reads as
// unnamed — the node then falls back to a name both sides derive the same way.
func funcInfo[F any](fn F) (p pos, short string) {
	v := reflect.ValueOf(fn)
	if v.Kind() != reflect.Func || v.IsNil() {
		return pos{}, ""
	}
	f := runtime.FuncForPC(v.Pointer())
	if f == nil {
		return pos{}, ""
	}
	qualified := f.Name()
	file, line := f.FileLine(f.Entry())
	if !strings.HasPrefix(file, "<") {
		p = pos{file: file, line: line, fn: qualified}
	}
	// Strip the package path, then an instantiation suffix.
	rest := qualified[strings.LastIndex(qualified, "/")+1:]
	_, rest, _ = strings.Cut(rest, ".")
	rest, _, _ = strings.Cut(rest, "[")
	if strings.HasSuffix(qualified, "-fm") {
		// A method value: (*T).M-fm or T.M-fm. The name is the method's.
		rest = strings.TrimSuffix(rest, "-fm")
		rest = rest[strings.LastIndex(rest, ".")+1:]
		return p, rest
	}
	if isClosureName(qualified) || strings.Contains(rest, ".") || rest == "" {
		return p, ""
	}
	return p, rest
}

// nodeBase holds what every building block has.
type nodeBase struct {
	svc  *Service
	kind model.NodeKind
	name string
	id   string
	decl pos
	// body is where the function the node runs starts, when it has one.
	body *pos
}

// base is what every node shares.
func (n *nodeBase) base() *nodeBase { return n }

// ID returns the node's identifier in the product graph:
// "<service>/<kind>/<name>".
func (n *nodeBase) ID() string { return n.id }

// app returns the running app the node's service is mounted in, or nil.
func (n *nodeBase) app() *App { return n.svc.app.Load() }

// ctxKey carries the node currently doing work, and the app it runs in.
type ctxKey struct{}

type nodeCtx struct {
	id  string
	app *App
}

// withNode returns ctx marked as running inside the node with the given ID,
// in app a. Every primitive a handler touches reads it back to know which
// edge it is travelling: that is how the diagram observes itself.
func withNode(ctx context.Context, id string, a *App) context.Context {
	return context.WithValue(ctx, ctxKey{}, nodeCtx{id: id, app: a})
}

// currentNode returns the node ctx runs inside, or "".
func currentNode(ctx context.Context) string {
	n, _ := ctx.Value(ctxKey{}).(nodeCtx)
	return n.id
}

// appOf returns the app ctx runs inside, or nil.
func appOf(ctx context.Context) *App {
	n, _ := ctx.Value(ctxKey{}).(nodeCtx)
	return n.app
}
