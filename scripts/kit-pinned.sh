#!/usr/bin/env bash
# kit-pinned.sh — sourced, never run: what scripts/regen.sh,
# scripts/from-zero.sh and scripts/kit-coverage.sh share (ADR 0169), so the
# three decide alike. The caller is at the repository root.
#
#   - `kit_pinned NAME` refuses, naming NAME, unless `kit` on PATH is the
#     version design/sdk.yaml pins (project.kit.version), and sets KIT_PINNED
#     to it;
#   - KIT_HEADER is the first line of every file kit generates, as a bash
#     regular expression — the line tools/genindex/digests.go's kitHeader
#     matches;
#   - `kit_clear_section FILE` removes kit's `# BEGIN kit gen` … `# END kit
#     gen` section of FILE (tools/alloc-lane-targets.txt, ADR 0165) and the
#     blank line kit gen adds above it, every other line kept byte for byte.
#
# Runs under macOS's /bin/bash 3.2 and the BSD tools (scripts/CLAUDE.md).

kit_pinned() {
  local name="$1" want have
  want="$(awk '
    /^project:/ { p = 1; next }
    p && /^[^ #]/ { p = 0 }
    p && /^  kit:/ { k = 1; next }
    k && /^  [^ #]/ { k = 0 }
    k && /^    version:/ { print $2; exit }
  ' design/sdk.yaml)"
  if [ -z "$want" ]; then
    printf '%s: design/sdk.yaml pins no kit (project.kit.version)\n' "$name" >&2
    return 1
  fi
  if ! command -v kit >/dev/null 2>&1; then
    printf '%s: kit is not on PATH; install kit %s (kitsunium/platform) and retry\n' "$name" "$want" >&2
    return 1
  fi
  if ! have="$(kit version 2>/dev/null | awk 'NR == 1 { print $2 }')"; then
    printf '%s: kit version failed; cannot verify the pinned kit %s\n' "$name" "$want" >&2
    return 1
  fi
  if [ "$have" != "$want" ]; then
    printf '%s: kit on PATH is %s, design/sdk.yaml pins %s; install kit %s and retry\n' "$name" "${have:-unknown}" "$want" "$want" >&2
    return 1
  fi
  export KIT_PINNED="$want"
}

# Read by the scripts that source this file.
# shellcheck disable=SC2034
KIT_HEADER='^// Code generated by kit from [^ ]+ \(sha256 [0-9a-f]{64}, body [0-9a-f]{64}\)\. DO NOT EDIT\.$'

kit_clear_section() {
  local file="$1"
  grep -q '^# BEGIN kit gen' "$file" || return 0
  awk '
    s { if (/^# END kit gen/) s = 0; next }
    /^# BEGIN kit gen/ { h = 0; s = 1; next }
    { if (h) print ""; h = 0 }
    /^$/ { h = 1; next }
    { print }
    END { if (h) print "" }
  ' "$file" >"$file.kit-section" && cat "$file.kit-section" >"$file" && rm -f "$file.kit-section"
}
