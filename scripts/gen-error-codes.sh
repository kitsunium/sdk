#!/usr/bin/env bash
# gen-error-codes.sh — regenerate docs/error-codes.yaml from the errs.Code
# constants declared across the tree. This YAML is the human-readable mirror
# of the dotted-quad registry; the EXECUTABLE source of truth stays the AST
# audit in internal/kernel/errs/registry_external_test.go (ADR 0005/0006).
#
# Run via `make error-codes`. The pre-commit guard
# scripts/pre-commit/check-error-codes-drift.sh fails the commit when the
# committed YAML no longer matches what this script would produce, so the
# registry never silently drifts from the code (CLAUDE.md rule 11).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/docs/error-codes.yaml"

cd "$root"

{
	echo "# GENERATED by scripts/gen-error-codes.sh — DO NOT EDIT BY HAND."
	echo "# Regenerate with: make error-codes"
	echo "#"
	echo "# Human-readable mirror of the SDK dotted-quad error-code registry"
	echo "# (MM.LL.PP.SS, ADR 0005/0006). One entry per errs.Code constant. The"
	echo "# executable source of truth is the AST audit in"
	echo "# internal/kernel/errs/registry_external_test.go."
	echo "codes:"
	# Match: <ConstName> errs.Code = 0x.. // <dotted-quad>. Keep the file path
	# (no -h) so we can attribute each code to its package, then drop tests.
	grep -rnE '[A-Za-z0-9_]+ +errs\.Code = 0x[0-9A-Fa-f_]+ +// +[0-9]+\.[0-9]+\.[0-9]+' \
		--include='*.go' internal pkg third-party |
		grep -v '_test.go:' |
		sed -E 's#^([^:]+):[0-9]+:.*[[:space:]]([A-Za-z0-9_]+) +errs\.Code = (0x[0-9A-Fa-f_]+) +// +([0-9.]+).*#\4|\2|\3|\1#' |
		sort -t'|' -k1V |
		while IFS='|' read -r dotted name hex file; do
			pkg="$(dirname "$file")"
			printf '  - code: "%s"\n    const: %s\n    hex: "%s"\n    package: %s\n' \
				"$dotted" "$name" "$hex" "$pkg"
		done
} >"$out"

echo "wrote $out ($(grep -c '  - code:' "$out") entries)"
